export const TITLE_BY_ID = Object.fromEntries(TITLES.map(t => [t.id, t]));
/** 称号のidとして正しいか（サーバーや他の参加者から届く値の検査に使う） */
export const isTitleId = id => typeof id === 'string' && Object.hasOwn(TITLE_BY_ID, id);
export const titleName = id => (isTitleId(id) ? TITLE_BY_ID[id].n : '');

/**
 * バトルが終わったときの判定。c.totals は「このバトルを数えたあと」の積み重ね。取った称号の id の一覧を返す
 */
export function evaluateTitles(c) {
  const ctx = { all: [], ...c };
  const out = [];
  for (const t of TITLES) { try { if (t.f(ctx)) out.push(t.id); } catch { /* 記録が足りないときは、取れない */ } }
  return out;
}

/** バトルの結果を、積み重ね（totals）に足す。参加者として最後まで遊んだバトルを1回数える */
export function addToTotals(totals, { s, u, result }) {
  const t = { plays: 0, chat: 0, hosted: 0, bankSent: 0, ...totals, winJobs: [...(totals?.winJobs || [])], bosses: [...(totals?.bosses || [])] };
  t.plays++;
  if ((s?.won || 0) > 0) {
    if (u && SELECTABLE.includes(u.job) && !t.winJobs.includes(u.job)) t.winJobs.push(u.job);
    for (const b of result?.bosses || []) if (!t.bosses.includes(b)) t.bosses.push(b);
  }
  return t;
}
